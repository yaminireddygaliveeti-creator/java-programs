package array;

public class apcode {
	    public static int calculate(int a, int b) {
	        return (a * b) +3;
	    }

	    public static void main(String[] args) {
	        System.out.println("6,5 = " + calculate(6, 5));
	        System.out.println("7,2 = " + calculate(7, 2));
	        System.out.println("11,4 = " + calculate(11, 4));
	        System.out.println("3,8 = " + calculate(3, 8));
	    }
	}


